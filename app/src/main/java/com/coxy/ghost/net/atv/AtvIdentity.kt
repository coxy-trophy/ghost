package com.coxy.ghost.net.atv

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Log
import java.math.BigInteger
import java.net.Socket
import java.security.KeyStore
import java.security.Principal
import java.security.PrivateKey
import java.security.cert.X509Certificate
import java.security.interfaces.RSAPublicKey
import java.util.Calendar
import javax.net.ssl.SSLContext
import javax.net.ssl.SSLSocket
import javax.net.ssl.X509ExtendedKeyManager
import javax.net.ssl.X509TrustManager
import javax.security.auth.x500.X500Principal

/**
 * GHOST's identity to a television, and the TLS that carries it.
 *
 * Pairing is a certificate exchange, not a password: the TV remembers the client certificate it was
 * shown while the on-screen code was entered, and thereafter lets that certificate in without
 * asking again. So the certificate *is* the pairing. It is generated once, kept in the
 * AndroidKeyStore where the private key cannot be read back out even by this app, and reused for
 * every TV — which is why re-pairing is only ever needed per television, not per session.
 *
 * The key is generated by the AndroidKeyStore rather than assembled here because generating a key
 * is easy and hand-encoding a self-signed X.509 in DER is not: there is no `sun.security.x509` on
 * Android, and the platform will produce a valid self-signed certificate for a generated key as a
 * side effect of asking for one.
 *
 * The trust manager accepts any server certificate, and that is correct rather than lazy. A
 * television's certificate is self-signed by the device itself; there is no authority to check it
 * against, and every implementation of this protocol does the same. What actually authenticates the
 * TV is the pairing hash — both sides prove they are looking at the same two certificates and the
 * same on-screen code, which a man in the middle cannot fake without the code.
 */
internal object AtvIdentity {

    private const val TAG = "AtvIdentity"
    /**
     * Version-suffixed because the first spec produced a key the platform would not sign with.
     * A key's spec is fixed at generation, so widening it means a new key — and a new key means
     * re-pairing every television, which is why it is worth getting the spec right in one go.
     */
    private const val ALIAS = "ghost-atv-remote-v3"
    private val SUPERSEDED = listOf("ghost-atv-remote", "ghost-atv-remote-v2")

    /** The certificate and key GHOST presents to every television. Created on first use. */
    fun entry(): KeyStore.PrivateKeyEntry {
        val ks = KeyStore.getInstance("AndroidKeyStore").apply { load(null) }
        (ks.getEntry(ALIAS, null) as? KeyStore.PrivateKeyEntry)?.let { return it }
        // Earlier keys could never complete a handshake; leaving them would be dead entries.
        SUPERSEDED.forEach { old -> runCatching { if (ks.containsAlias(old)) ks.deleteEntry(old) } }

        Log.i(TAG, "generating GHOST's remote-control certificate")
        val end = Calendar.getInstance().apply { add(Calendar.YEAR, 25) }
        val generator = java.security.KeyPairGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_RSA, "AndroidKeyStore"
        )
        generator.initialize(
            KeyGenParameterSpec.Builder(
                ALIAS,
                KeyProperties.PURPOSE_SIGN or KeyProperties.PURPOSE_VERIFY or
                    KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
            )
                .setKeySize(2048)
                // DIGEST_NONE is the one that matters and the one that was missing. TLS 1.2 client
                // authentication signs an already-computed hash with NONEwithRSA, so a key allowed
                // only SHA-256 and SHA-1 refuses the operation — surfacing as
                // "RSA routines: internal error" out of Conscrypt, which names neither the key nor
                // the digest. The rest are permitted so a future TLS version does not repeat this.
                .setDigests(
                    KeyProperties.DIGEST_NONE,
                    KeyProperties.DIGEST_SHA1,
                    KeyProperties.DIGEST_SHA256,
                    KeyProperties.DIGEST_SHA384,
                    KeyProperties.DIGEST_SHA512
                )
                .setSignaturePaddings(
                    KeyProperties.SIGNATURE_PADDING_RSA_PKCS1,
                    KeyProperties.SIGNATURE_PADDING_RSA_PSS
                )
                // ENCRYPTION_PADDING_NONE is the one TLS actually needs, and the least obvious.
                // Conscrypt performs client-authentication signing by running the private key
                // through Cipher with "RSA/ECB/NoPadding" — an *encryption* padding, not a
                // signature one — so a key that permits every signature padding and not this one
                // still fails, with "Incompatible padding mode" buried in a CryptoUpcalls warning
                // while the visible error stays the same opaque RSA internal error.
                .setEncryptionPaddings(
                    KeyProperties.ENCRYPTION_PADDING_NONE,
                    KeyProperties.ENCRYPTION_PADDING_RSA_PKCS1
                )
                .setRandomizedEncryptionRequired(false)
                // Certificate validity has to outlast the pairing: a TV that trusts an expired
                // certificate is a TV that silently stops answering one day.
                .setCertificateSubject(X500Principal("CN=GHOST"))
                .setCertificateSerialNumber(BigInteger.valueOf(1))
                .setCertificateNotAfter(end.time)
                .build()
        )
        generator.generateKeyPair()
        return ks.getEntry(ALIAS, null) as KeyStore.PrivateKeyEntry
    }

    /** The RSA modulus and exponent of GHOST's own certificate, for the pairing hash. */
    fun clientRsa(): Pair<ByteArray, ByteArray> {
        val cert = entry().certificate as X509Certificate
        return rsaParts(cert)
    }

    /** Same, for whatever certificate the television presented on this connection. */
    fun serverRsa(socket: SSLSocket): Pair<ByteArray, ByteArray> {
        val peer = socket.session.peerCertificates.firstOrNull() as? X509Certificate
            ?: throw IllegalStateException("the television presented no certificate")
        return rsaParts(peer)
    }

    /**
     * Modulus and exponent as unsigned big-endian bytes.
     *
     * `BigInteger.toByteArray()` prepends a zero byte whenever the top bit is set, to keep the
     * value positive — which it is for every 2048-bit modulus. Leaving that byte in changes the
     * hash, and the failure is a `STATUS_BAD_SECRET` from the TV with nothing to say why.
     */
    private fun rsaParts(cert: X509Certificate): Pair<ByteArray, ByteArray> {
        val key = cert.publicKey as? RSAPublicKey
            ?: throw IllegalStateException("expected an RSA certificate")
        return unsigned(key.modulus) to unsigned(key.publicExponent)
    }

    private fun unsigned(v: BigInteger): ByteArray {
        val raw = v.toByteArray()
        return if (raw.size > 1 && raw[0] == 0.toByte()) raw.copyOfRange(1, raw.size) else raw
    }

    /** A TLS socket to [host]:[port] presenting GHOST's certificate. */
    fun connect(host: String, port: Int, timeoutMs: Int): SSLSocket {
        val entry = entry()
        val chain = entry.certificateChain.map { it as X509Certificate }.toTypedArray()

        val keyManager = object : X509ExtendedKeyManager() {
            override fun getClientAliases(keyType: String?, issuers: Array<out Principal>?) =
                arrayOf(ALIAS)

            override fun chooseClientAlias(
                keyType: Array<out String>?, issuers: Array<out Principal>?, socket: Socket?
            ) = ALIAS

            override fun getServerAliases(keyType: String?, issuers: Array<out Principal>?) = null
            override fun chooseServerAlias(
                keyType: String?, issuers: Array<out Principal>?, socket: Socket?
            ) = null

            override fun getCertificateChain(alias: String?) = chain
            override fun getPrivateKey(alias: String?): PrivateKey = entry.privateKey
        }

        // See the note on this object: a television's certificate is self-signed by the television.
        val trustAll = object : X509TrustManager {
            override fun checkClientTrusted(chain: Array<out X509Certificate>?, authType: String?) = Unit
            override fun checkServerTrusted(chain: Array<out X509Certificate>?, authType: String?) = Unit
            override fun getAcceptedIssuers(): Array<X509Certificate> = emptyArray()
        }

        val ctx = SSLContext.getInstance("TLS").apply {
            init(arrayOf(keyManager), arrayOf(trustAll), java.security.SecureRandom())
        }
        val socket = ctx.socketFactory.createSocket() as SSLSocket
        // Pinned to TLS 1.2: client authentication there is PKCS#1 over a pre-hashed value, which
        // an AndroidKeyStore key does cleanly. TLS 1.3 mandates RSA-PSS, which these keys handle
        // less predictably across vendors, and a television gains nothing from the newer version.
        runCatching { socket.enabledProtocols = arrayOf("TLSv1.2") }
        socket.connect(java.net.InetSocketAddress(host, port), timeoutMs)
        socket.soTimeout = timeoutMs
        socket.startHandshake()
        return socket
    }
}
